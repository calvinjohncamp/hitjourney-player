window.hjApplyHomeAlbumSequence = function(albums, songs){
  if(!albums.home) return;
  const bySlug = new Map(songs.map(song => [song.slug, song]));
  const ordered = window.HJ_HOME_ALBUM_SEQUENCE.map(slug => bySlug.get(slug)).filter(Boolean);
  if(!ordered.length) return;
  albums.home.songs = ordered.map((song, i) => ({...song, _position:i+1}));
  albums.home.meta = ordered.length + " Songs";
};
